/** Текст события: абзац источника и, если указано, следующий за ним список. Нет абзаца — ошибка сида, а не пустое событие. */
export function timelineText(e: TimelineSeed): string {
  const i = ARCHIVE_HISTORY_RU.findIndex((b) => b.type === 'p' && b.text.startsWith(e.from));
  const block = ARCHIVE_HISTORY_RU[i];
  if (!block || block.type !== 'p') throw new Error(`Хронология: нет абзаца «${e.from}»`);
  if (!block.text.includes(String(e.year))) throw new Error(`Хронология: в абзаце «${e.from}» нет года ${e.year}`);
  const next = ARCHIVE_HISTORY_RU[i + 1];
  const list = e.withList && next && (next.type === 'ol' || next.type === 'ul') ? next.items.map((x) => `— ${x}`).join('\n') : '';
  return list ? `${block.text}\n${list}` : block.text;
}
